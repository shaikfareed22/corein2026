#!/usr/bin/env python3
"""Generate the FOMO launcher and status-bar icons for android/ from assets/brand/.

Idempotent; re-run after every upstream pull (CONTRIBUTING.md). Writes:

- drawable/ic_launcher_foreground_nm.xml       the O and the orange arrow, 108dp canvas
- drawable/ic_launcher_foreground_nm_dark.xml  the same path, white (the "Dark" icon skin)
- drawable/ic_launcher_monochrome.xml          the same path, flat (Android 13+ themed icons)
- drawable/ic_stat_nanomuse.xml                24dp flat mark for notification small icons
- mipmap-anydpi-v26/ic_launcher*.xml           the three adaptive icons (auto / light / dark)
- values*/ic_launcher_background.xml, values/ic_launcher_alt_colors.xml  tile colours
- mipmap-*/ic_launcher*.png                    legacy rasters, when Playwright is installed

Geometry: the mark's tile is 0..100 units == the 72dp visible area of a 108dp adaptive
icon, so x' = 18 + 0.72 * x. The farthest point of the mark from the centre is ~29dp,
inside the 33dp circle that themed icons and round masks keep.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BRAND = ROOT / "assets" / "brand"
RES = ROOT / "android" / "src" / "android" / "app" / "src" / "main" / "res"

TILE = "#1C2932"  # the logo's navy: the launcher tile, every skin
PRIMARY = "#FFFFFF"  # the O
ACCENT = "#FF9A18"  # the arrow
OUTLINE = 3.5  # the arrow's outline in the tile colour, in mark units, as in the logo
# kept for scripts/gen-ios-icons.py and older callers
TILE_LIGHT = TILE
TILE_DARK = TILE
STROKE_START = PRIMARY
STROKE_END = PRIMARY
SCALE, OFFSET = 0.72, 18.0
TOKEN = re.compile(r"[MLCZ]|-?\d*\.?\d+")
MARK = BRAND / "fomo-mark.svg"


def mark_paths() -> tuple[str, str]:
    """The O and the arrow of assets/brand/fomo-mark.svg (paths id="primary" and id="accent")."""
    svg = MARK.read_text(encoding="utf-8")
    found = {}
    for tag in re.findall(r"<path\b[^>]*>", svg):
        pid = re.search(r'\sid="([^"]+)"', tag)
        d = re.search(r'\sd="([^"]+)"', tag)
        if pid and d:
            found[pid.group(1)] = d.group(1)
    if "primary" not in found or "accent" not in found:
        sys.exit(f"{MARK.relative_to(ROOT)}: needs a primary and an accent path")
    return found["primary"], found["accent"]


def mark_path() -> str:
    """Both shapes as one path, for the single-colour places (monochrome, notification)."""
    primary, accent = mark_paths()
    return primary + accent


def transform(d: str, scale: float, ox: float, oy: float | None = None) -> str:
    """Absolute M/L/C/Z path data, scaled and translated, 2 decimals."""
    if oy is None:
        oy = ox
    text = ""
    n = 0
    for tok in TOKEN.findall(d):
        if tok in "MLCZ":
            text += tok
        else:
            offset = ox if n % 2 == 0 else oy
            text += f"{offset + scale * float(tok):.2f} "
            n += 1
    return re.sub(r" (?=[MLCZ])", "", text).strip()


def path_bbox(d: str) -> tuple[float, float, float, float]:
    nums = [float(t) for t in TOKEN.findall(d) if t not in "MLCZ"]
    xs, ys = nums[0::2], nums[1::2]
    return min(xs), min(ys), max(xs), max(ys)


def argb(hex_rgb: str) -> str:
    return "#FF" + hex_rgb[1:]


def vector(paths: list[str], size: int, viewport: int, comment: str) -> str:
    body = "\n".join(paths)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- FOMO: {comment} Generated by scripts/gen-android-icons.py from
     assets/brand/fomo-mark.svg; do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp" android:height="{size}dp"
    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">
{body}
</vector>
"""


def vpath(d: str, fill: str, stroke: str | None = None, width: float = 0.0) -> str:
    extra = ""
    if stroke:
        extra = (
            f'\n        android:strokeColor="{stroke}" android:strokeWidth="{width:.2f}"'
            ' android:strokeLineJoin="round"'
        )
    return f'    <path android:pathData="{d}"\n        android:fillColor="{fill}"{extra} />'


def adaptive(background: str, foreground: str) -> str:
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- FOMO: generated by scripts/gen-android-icons.py. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="{background}" />
    <foreground android:drawable="{foreground}" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8")
        print(f"  wrote {path.relative_to(ROOT)}")


def set_color(path: Path, name: str, value: str) -> None:
    text = path.read_text(encoding="utf-8")
    new = re.sub(rf'(<color name="{name}">)#[0-9A-Fa-f]+(</color>)', rf"\g<1>{value}\g<2>", text)
    if new != text:
        path.write_text(new, encoding="utf-8")
        print(f"  {path.relative_to(ROOT)}: {name} = {value}")


def vectors() -> None:
    primary, accent = mark_paths()
    o108, a108 = transform(primary, SCALE, OFFSET), transform(accent, SCALE, OFFSET)
    colour = [vpath(o108, argb(PRIMARY)), vpath(a108, argb(ACCENT), argb(TILE), OUTLINE * SCALE)]
    drawable = RES / "drawable"
    write(
        drawable / "ic_launcher_foreground_nm.xml",
        vector(colour, 108, 108, "launcher foreground, the O and the arrow."),
    )
    write(
        drawable / "ic_launcher_foreground_nm_dark.xml",
        vector(colour, 108, 108, "launcher foreground for the Dark icon skin."),
    )
    write(
        drawable / "ic_launcher_monochrome.xml",
        vector(
            [vpath(o108 + a108, "#FFFFFFFF")],
            108,
            108,
            "themed-icon silhouette; the system re-tints it.",
        ),
    )
    # 24dp status-bar icon: the mark in a 20dp box centred on the 24dp canvas (an alpha mask).
    d = primary + accent
    bx0, by0, bx1, by1 = path_bbox(d)
    scale = 20 / max(bx1 - bx0, by1 - by0)
    p24 = transform(d, scale, 12 - scale * (bx0 + bx1) / 2, 12 - scale * (by0 + by1) / 2)
    write(
        drawable / "ic_stat_nanomuse.xml",
        vector([vpath(p24, "#FFFFFFFF")], 24, 24, "notification small icon (alpha mask)."),
    )
    anydpi = RES / "mipmap-anydpi-v26"
    write(
        anydpi / "ic_launcher.xml",
        adaptive("@color/ic_launcher_background", "@drawable/ic_launcher_foreground_nm"),
    )
    write(
        anydpi / "ic_launcher_classic_light.xml",
        adaptive("@color/ic_launcher_bg_force_light", "@drawable/ic_launcher_foreground_nm"),
    )
    write(
        anydpi / "ic_launcher_classic_dark.xml",
        adaptive("@color/ic_launcher_bg_force_dark", "@drawable/ic_launcher_foreground_nm_dark"),
    )
    set_color(RES / "values" / "ic_launcher_background.xml", "ic_launcher_background", TILE)
    set_color(RES / "values-night" / "ic_launcher_background.xml", "ic_launcher_background", TILE)
    set_color(RES / "values" / "ic_launcher_alt_colors.xml", "ic_launcher_bg_force_light", TILE)
    set_color(RES / "values" / "ic_launcher_alt_colors.xml", "ic_launcher_bg_force_dark", TILE)


def mark_svg(
    viewbox: int, primary: str, accent: str, outline: float, tile: str | None, rx: float = 0
) -> str:
    back = ""
    if tile:
        back = f'<rect width="{viewbox}" height="{viewbox}" rx="{rx}" ry="{rx}" fill="{tile}"/>'
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {viewbox} {viewbox}">{back}'
        f'<path d="{primary}" fill="{PRIMARY}"/>'
        f'<path d="{accent}" fill="{ACCENT}" stroke="{TILE}" stroke-width="{outline:.2f}"'
        ' stroke-linejoin="round"/></svg>'
    )


def rasters() -> None:
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        print("  playwright not installed: legacy PNG icons left as they are")
        return
    primary, accent = mark_paths()
    densities = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}
    tile = mark_svg(100, primary, accent, OUTLINE, TILE, rx=22)
    fg = mark_svg(
        108,
        transform(primary, SCALE, OFFSET),
        transform(accent, SCALE, OFFSET),
        OUTLINE * SCALE,
        None,
    )
    jobs: list[tuple[Path, str, int]] = []
    for name, k in densities.items():
        for prefix in ("mipmap", "mipmap-night"):
            folder = RES / f"{prefix}-{name}"
            if not folder.is_dir():
                continue
            for icon in ("ic_launcher.png", "ic_launcher_round.png"):
                if (folder / icon).exists():
                    jobs.append((folder / icon, tile, round(48 * k)))
            for fg_name in (
                "ic_launcher_foreground.png",
                "ic_launcher_foreground_light.png",
                "ic_launcher_foreground_dark.png",
            ):
                if (folder / fg_name).exists():
                    jobs.append((folder / fg_name, fg, round(108 * k)))
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page()
        for target, svg, px in jobs:
            page.set_viewport_size({"width": px, "height": px})
            page.set_content(f'<body style="margin:0;background:transparent">{svg}</body>')
            page.locator("svg").evaluate(
                "(e, s) => { e.setAttribute('width', s); e.setAttribute('height', s); }", str(px)
            )
            page.screenshot(
                path=str(target),
                omit_background=True,
                clip={"x": 0, "y": 0, "width": px, "height": px},
            )
        browser.close()
    print(f"  {len(jobs)} legacy PNGs rendered")


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    if args in (["-h"], ["--help"]):
        print(__doc__.strip())
        return 0
    if args:
        print(
            f"usage: {sys.argv[0]}  (takes no arguments; unknown: {' '.join(args)})",
            file=sys.stderr,
        )
        return 2
    print("== launcher icons")
    vectors()
    rasters()
    return 0


if __name__ == "__main__":
    sys.exit(main())
